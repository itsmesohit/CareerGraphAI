export async function seedCanonicalQuestions() {
  console.log(`Seeding ${CANONICAL_QUESTIONS.length} canonical questions into database...`);

  let count = 0;
  for (const q of CANONICAL_QUESTIONS) {
    await prisma.canonicalQuestion.upsert({
      where: { key: q.key },
      create: {
        key: q.key,
        category: q.category,
        questionText: q.questionText,
        helpText: q.helpText,
        answerType: q.answerType,
        options: q.options ? JSON.stringify(q.options) : undefined,
        sensitivity: q.sensitivity,
        isCoreOnboarding: q.isCoreOnboarding,
      },
      update: {
        category: q.category,
        questionText: q.questionText,
        helpText: q.helpText,
        answerType: q.answerType,
        options: q.options ? JSON.stringify(q.options) : undefined,
        sensitivity: q.sensitivity,
        isCoreOnboarding: q.isCoreOnboarding,
      },
    });
    count++;
  }

  console.log(`✓ Successfully seeded ${count} canonical universal questions.`);
}
